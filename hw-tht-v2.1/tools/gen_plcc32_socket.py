#!/usr/bin/env python3
"""Generate a simple 3D model of a through-hole PLCC-32 socket with a PLCC-32 chip in it (PicoGUS v2.1 THT boot ROM).

  python3 hw-tht-v2.1/tools/gen_plcc32_socket.py

Writes hw-common/parts/PLCC-32_THT-Socket.wrl, for KiCad's footprint Package_LCC:PLCC-32_THT-Socket (origin at pin 1,
offset 0, rotate 0). KiCad's own library has no model for this footprint. The model is for the renders only: frame,
contacts, pins, the chip (11.43 x 13.97 mm) and a paper label; the outline is the footprint's (body 18.0 x 20.56 mm,
its silkscreen outline less the margin), the heights are assumed (frame 4.6 mm, chip top 4.9 mm above the board):
check the real socket's height where it matters.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'hw-common', 'parts', 'PLCC-32_THT-Socket.wrl')

# footprint coordinates (mm, y down), origin at pin 1
PADS_X = [-7.62, -5.08, -2.54, 0.0, 2.54, 5.08]
PADS_Y = [-2.54, 0.0, 2.54, 5.08, 7.62, 10.16, 12.7]
# pad positions as in the footprint: outer ring and inner ring of the staggered pattern
PADS = ([(x, -2.54) for x in PADS_X[1:5]] + [(x, 0.0) for x in PADS_X] +
        [(x, y) for y in PADS_Y[2:5] for x in (-7.62, -5.08, 2.54, 5.08)] +
        [(x, 10.16) for x in PADS_X] + [(x, 12.7) for x in PADS_X[1:5]])
CX, CY = -1.27, 5.08                    # centre of the pin pattern = centre of socket and chip
BODY = (-10.27, -5.2, 7.73, 15.36)      # socket frame
CHIP_W, CHIP_H = 11.43, 13.97
BLACK, CHIPC, TIN, PAPER = (0.13, 0.12, 0.12), (0.22, 0.22, 0.23), (0.78, 0.78, 0.80), (0.92, 0.90, 0.82)


def wrl():
    P = 2.54
    shapes = []

    def box(x1, y1, z1, x2, y2, z2, rgb, shin=0.2):
        X = [v / P for v in (x1, x2)]
        Y = [-v / P for v in (y1, y2)]
        Z = [v / P for v in (z1, z2)]
        shapes.append(([(X[i], Y[j], Z[k]) for k in (0, 1) for j in (0, 1) for i in (0, 1)], rgb, shin))

    x1, y1, x2, y2 = BODY
    cav = (CX - CHIP_W / 2 - 0.9, CY - CHIP_H / 2 - 0.9, CX + CHIP_W / 2 + 0.9, CY + CHIP_H / 2 + 0.9)   # chip + contacts
    top = 4.6
    box(x1, y1, 0.3, x2, y2, 1.2, BLACK)                         # floor
    box(x1, y1, 1.2, x2, cav[1], top, BLACK)                     # four walls
    box(x1, cav[3], 1.2, x2, y2, top, BLACK)
    box(x1, cav[1], 1.2, cav[0], cav[3], top, BLACK)
    box(cav[2], cav[1], 1.2, x2, cav[3], top, BLACK)
    for k in range(7):                                           # contacts: 7 on the short sides, 9 on the long ones
        x = CX + (k - 3) * 1.27
        box(x - 0.22, cav[1], 1.2, x + 0.22, cav[1] + 0.85, top - 0.3, TIN, 0.7)
        box(x - 0.22, cav[3] - 0.85, 1.2, x + 0.22, cav[3], top - 0.3, TIN, 0.7)
    for k in range(9):
        y = CY + (k - 4) * 1.27
        box(cav[0], y - 0.22, 1.2, cav[0] + 0.85, y + 0.22, top - 0.3, TIN, 0.7)
        box(cav[2] - 0.85, y - 0.22, 1.2, cav[2], y + 0.22, top - 0.3, TIN, 0.7)
    box(CX - CHIP_W / 2, CY - CHIP_H / 2, 1.4, CX + CHIP_W / 2, CY + CHIP_H / 2, 4.9, CHIPC, 0.3)       # the flash
    box(CX - 4.2, CY - 2.6, 4.9, CX + 4.2, CY + 3.4, 5.05, PAPER, 0.05)                                  # its label
    box(CX - 0.5, CY - CHIP_H / 2 + 0.7, 4.9, CX + 0.5, CY - CHIP_H / 2 + 1.5, 5.05, TIN, 0.5)          # pin 1 mark
    for x, y in PADS:                                            # pins through the board
        box(x - 0.25, y - 0.25, -3.2, x + 0.25, y + 0.25, 0.3, TIN, 0.7)
    faces = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
    out = ['#VRML V2.0 utf8',
           '# Through-hole PLCC-32 socket with a PLCC-32 chip - simple generated model: frame, contacts, pins, chip',
           '# For footprint Package_LCC:PLCC-32_THT-Socket (origin at pin 1), offset 0, rotate 0.',
           '# Generated by hw-tht-v2.1/tools/gen_plcc32_socket.py.',
           '# Coordinates are in KiCad VRML units (1 = 0.1 inch = 2.54 mm); no Transform node on purpose.']
    for pts, rgb, shin in shapes:
        out.append('Shape {\n appearance Appearance {\n  material Material {\n'
                   f'   diffuseColor {rgb[0]:.3f} {rgb[1]:.3f} {rgb[2]:.3f}\n'
                   '   specularColor 0.200 0.200 0.200\n'
                   f'   shininess {shin}\n  }}\n }}\n geometry IndexedFaceSet {{\n  solid TRUE\n'
                   '  coord Coordinate { point [\n' +
                   ',\n'.join(f'   {x:.5f} {y:.5f} {z:.5f}' for x, y, z in pts) +
                   ' ] }\n  coordIndex [ ' +
                   ', '.join(' '.join(str(i) for i in f) + ' -1' for f in faces) + ' ]\n }\n}')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    assert len(PADS) == 32 and len(set(PADS)) == 32
    open(OUT, 'w').write(wrl())
    print('wrote', OUT)
